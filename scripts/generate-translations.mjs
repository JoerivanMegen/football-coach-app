import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { parse } from "yaml";

const projectRoot = process.cwd();
const sourceRoot = path.join(projectRoot, "src/i18n/translations");
const outputPath = path.join(projectRoot, "src/i18n/generated/translations.ts");
const locales = ["en", "nl"];

function loadLocale(locale) {
  const localeDirectory = path.join(sourceRoot, locale);
  return Object.fromEntries(
    fs.readdirSync(localeDirectory)
      .filter((fileName) => fileName.endsWith(".yaml"))
      .sort()
      .map((fileName) => {
        const section = path.basename(fileName, ".yaml");
        return [section, parse(fs.readFileSync(path.join(localeDirectory, fileName), "utf8"))];
      }),
  );
}

function flattenKeys(value, prefix = "") {
  return Object.entries(value).flatMap(([key, child]) => {
    const nextKey = prefix ? `${prefix}.${key}` : key;
    return child && typeof child === "object"
      ? flattenKeys(child, nextKey)
      : [nextKey];
  });
}

const dictionaries = Object.fromEntries(locales.map((locale) => [locale, loadLocale(locale)]));
const englishKeys = flattenKeys(dictionaries.en).sort();

for (const locale of locales.slice(1)) {
  const localeKeys = flattenKeys(dictionaries[locale]).sort();
  const missing = englishKeys.filter((key) => !localeKeys.includes(key));
  const extra = localeKeys.filter((key) => !englishKeys.includes(key));
  if (missing.length || extra.length) {
    throw new Error(`${locale} translation keys do not match English. Missing: ${missing.join(", ") || "none"}. Extra: ${extra.join(", ") || "none"}.`);
  }
}

const output = `// Generated by scripts/generate-translations.mjs. Do not edit directly.\n\nexport const translations = ${JSON.stringify(dictionaries, null, 2)} as const;\n\nexport type TranslationKey =\n${englishKeys.map((key) => `  | ${JSON.stringify(key)}`).join("\n")};\n`;
fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, output);

